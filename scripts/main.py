"""
Tech Radar - Main Pipeline Orchestrator.

Luồng thực thi:
1. Đọc config/sources.json
2. Thu thập dữ liệu từ các nguồn qua fetchers.py
3. Chống trùng lặp qua data/seen_urls.json
4. Chấm điểm & tóm tắt tiếng Việt qua curator.py (Gemini API + fallback an toàn)
5. Ghi đè data/latest.json, nối lên đầu data/archive.json (tối đa 500 mục),
   và cập nhật data/seen_urls.json.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Any

# Đảm bảo import được các module cùng thư mục scripts/ khi chạy từ root repo
SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from curator import curate_items
from fetchers import canonicalize_url, fetch_all_sources, utc_now_iso

CONFIG_PATH = PROJECT_ROOT / "config" / "sources.json"
DATA_DIR = PROJECT_ROOT / "data"
LATEST_PATH = DATA_DIR / "latest.json"
ARCHIVE_PATH = DATA_DIR / "archive.json"
SEEN_PATH = DATA_DIR / "seen_urls.json"
BUNDLE_JS_PATH = DATA_DIR / "bundle.js"


def setup_logging() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        datefmt="%H:%M:%S",
    )


def load_json(path: Path, default: Any) -> Any:
    if not path.exists():
        return default
    try:
        with path.open("r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as exc:
        logging.warning("Could not parse %s (%s). Using default.", path, exc)
        return default


def save_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write("\n")


def save_bundle_js(path: Path, latest_payload: dict[str, Any], archive_payload: dict[str, Any]) -> None:
    """Xuất thêm bản mirror JS để mở trực tiếp index.html qua file:// không bị lỗi CORS."""
    path.parent.mkdir(parents=True, exist_ok=True)
    bundle = {"latest": latest_payload, "archive": archive_payload}
    encoded = json.dumps(bundle, ensure_ascii=False).replace("</script>", "<\\/script>")
    with path.open("w", encoding="utf-8") as f:
        f.write("// Auto-generated by scripts/main.py for file:// direct-open compatibility\n")
        f.write(f"window.__TECH_RADAR_DATA__ = {encoded};\n")


def parse_seen_urls(raw_seen: Any) -> dict[str, str]:
    """Đọc seen_urls.json dưới dạng dict {canonical_url: last_seen_iso}."""
    if isinstance(raw_seen, dict):
        if isinstance(raw_seen.get("urls"), dict):
            return {str(k): str(v) for k, v in raw_seen["urls"].items()}
        return {str(k): str(v) for k, v in raw_seen.items() if k != "updated_at"}
    if isinstance(raw_seen, list):
        now = utc_now_iso()
        return {str(u): now for u in raw_seen if u}
    return {}


def parse_archive_items(raw_archive: Any) -> list[dict[str, Any]]:
    if isinstance(raw_archive, dict) and isinstance(raw_archive.get("items"), list):
        return raw_archive["items"]
    if isinstance(raw_archive, list):
        return raw_archive
    return []


def run_pipeline(
    dry_run: bool = False,
    no_ai: bool = False,
    skip_seen: bool = False,
    max_candidates_override: int | None = None,
) -> dict[str, Any]:
    logger = logging.getLogger("tech_radar.main")

    if not CONFIG_PATH.exists():
        raise FileNotFoundError(f"Missing config file: {CONFIG_PATH}")

    config = load_json(CONFIG_PATH, {})
    if max_candidates_override is not None and max_candidates_override > 0:
        config.setdefault("curation", {})["max_candidates"] = max_candidates_override

    cur_cfg = config.get("curation", {})
    archive_limit = int(cur_cfg.get("archive_limit", 500))
    seen_limit = int(cur_cfg.get("seen_urls_limit", 5000))

    seen_map = parse_seen_urls(load_json(SEEN_PATH, {}))
    existing_archive = parse_archive_items(load_json(ARCHIVE_PATH, {}))

    logger.info("Starting Tech Radar fetch pipeline (seen_urls=%d, archive=%d)...", len(seen_map), len(existing_archive))
    raw_items, source_stats = fetch_all_sources(config)
    logger.info("Total raw items fetched: %d | Breakdown: %s", len(raw_items), source_stats)

    # Chống trùng lặp trong cùng batch và với seen_urls.json
    new_candidates: list[dict[str, Any]] = []
    batch_seen: set[str] = set()
    for item in raw_items:
        canon = item.get("canonical_url") or canonicalize_url(item.get("url", ""))
        if not canon or canon in batch_seen:
            continue
        batch_seen.add(canon)
        if not skip_seen and canon in seen_map:
            continue
        new_candidates.append(item)

    logger.info("New unseen candidates after deduplication: %d", len(new_candidates))

    curated_items, is_ai_curated = curate_items(new_candidates, config, force_fallback=no_ai)
    updated_at = utc_now_iso()

    # Nối tin mới lên đầu archive và chống trùng theo id/url, giới hạn 500 mục
    merged_archive: list[dict[str, Any]] = []
    archive_seen_ids: set[str] = set()
    for item in curated_items + existing_archive:
        item_id = item.get("id")
        if not item_id or item_id in archive_seen_ids:
            continue
        archive_seen_ids.add(item_id)
        merged_archive.append(item)
        if len(merged_archive) >= archive_limit:
            break

    # Cập nhật seen_urls với toàn bộ URL mới đã quét (tránh xử lý lại tin rác ở lần chạy sau)
    for canon in batch_seen:
        seen_map[canon] = updated_at

    # Giới hạn kích thước seen_urls theo thứ tự mới nhất
    if len(seen_map) > seen_limit:
        sorted_seen = sorted(seen_map.items(), key=lambda kv: kv[1], reverse=True)[:seen_limit]
        seen_map = dict(sorted_seen)

    latest_payload = {
        "updated_at": updated_at,
        "count": len(curated_items),
        "is_curated": is_ai_curated,
        "source_stats": source_stats,
        "items": curated_items,
    }
    archive_payload = {
        "updated_at": updated_at,
        "count": len(merged_archive),
        "items": merged_archive,
    }
    seen_payload = {
        "updated_at": updated_at,
        "count": len(seen_map),
        "urls": seen_map,
    }

    if dry_run:
        logger.info(
            "[DRY-RUN] Would write latest=%d, archive=%d, seen=%d (is_curated=%s).",
            len(curated_items),
            len(merged_archive),
            len(seen_map),
            is_ai_curated,
        )
    else:
        save_json(LATEST_PATH, latest_payload)
        save_json(ARCHIVE_PATH, archive_payload)
        save_json(SEEN_PATH, seen_payload)
        save_bundle_js(BUNDLE_JS_PATH, latest_payload, archive_payload)
        logger.info(
            "Saved data/latest.json (%d items), data/archive.json (%d items), data/seen_urls.json (%d urls), data/bundle.js.",
            len(curated_items),
            len(merged_archive),
            len(seen_map),
        )

    return {
        "fetched": len(raw_items),
        "new_candidates": len(new_candidates),
        "curated": len(curated_items),
        "archive_total": len(merged_archive),
        "seen_total": len(seen_map),
        "is_curated": is_ai_curated,
        "source_stats": source_stats,
    }


def main() -> int:
    setup_logging()
    parser = argparse.ArgumentParser(description="Tech Radar - Zero-Server Tech Curator Pipeline")
    parser.add_argument("--dry-run", action="store_true", help="Chạy thử không ghi đè thư mục data/")
    parser.add_argument("--no-ai", action="store_true", help="Bỏ qua Gemini API, dùng chế độ fallback")
    parser.add_argument("--skip-seen", action="store_true", help="Bỏ qua lọc trùng seen_urls.json")
    parser.add_argument("--max-candidates", type=int, default=None, help="Ghi đè số lượng ứng viên tối đa gửi AI")
    args = parser.parse_args()

    run_pipeline(
        dry_run=args.dry_run,
        no_ai=args.no_ai,
        skip_seen=args.skip_seen,
        max_candidates_override=args.max_candidates,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
